// Bundles the site template's vendor scripts into one file. The template loads ~20 separate
// libraries (jQuery, Bootstrap, Owl, GSAP…) that must run in a fixed order, so a page makes 20 JS
// requests before its own script.js can run. Concatenating them in the same order keeps the exact
// execution order (each library is a self-contained IIFE) while reducing it to a single request.
//
// Run via `npm run build:js` (also wired to predev/prebuild).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const JS_DIR = join(here, "..", "public", "site", "assets", "js");
const OUT = join(JS_DIR, "site-vendor.js");

// Exact load order from the template's <head>. Must stay in sync with the VENDOR list that used to
// live in components/site/SiteScripts.tsx.
const FILES = [
  "jquery-3.6.0.min.js",
  "bootstrap.bundle.min.js",
  "jarallax.min.js",
  "jquery.ajaxchimp.min.js",
  "jquery.appear.min.js",
  "swiper.min.js",
  "jquery.magnific-popup.min.js",
  "jquery.validate.min.js",
  "odometer.min.js",
  "wNumb.min.js",
  "wow.js",
  "isotope.js",
  "owl.carousel.min.js",
  "jquery-ui.js",
  "jquery.nice-select.min.js",
  "marquee.min.js",
  "aos.js",
  "gsap/gsap.js",
  "gsap/ScrollTrigger.js",
  "gsap/SplitText.js",
];

let out = "/* site vendor script bundle — generated by scripts/build-site-js.mjs. Do not edit. */\n";
for (const file of FILES) {
  const js = readFileSync(join(JS_DIR, file), "utf8");
  // A leading ";" terminates any statement a previous file left open; a trailing newline keeps the
  // next file's line comments from swallowing it.
  out += `\n/* ===== ${file} ===== */\n;${js.trimEnd()}\n`;
}
writeFileSync(OUT, out);
console.log(`[build-site-js] wrote ${FILES.length} files -> ${OUT} (${(out.length / 1024).toFixed(0)}KB)`);
