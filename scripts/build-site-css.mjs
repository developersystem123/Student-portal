// Bundles the site template's stylesheets into one file so a page makes a single CSS request
// instead of ~42. The template ships one file per module, and browsers must download (and the
// render-blocking critical path must wait on) every one of them.
//
// The concatenation order below is the order the template's own pages load them in, so the cascade
// is unchanged. Only files under public/site/assets/css/ are bundled — they all reference fonts
// and images relative to that directory, and the bundle is written back into the same directory, so
// every url() keeps resolving. The project's own layers (site-reset.css, site-brand.css,
// pages/*.css, site-dark.css) are hand-maintained and stay as separate files around the bundle.
//
// Run via `npm run build:css` (also wired to predev/prebuild).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const CSS_DIR = join(here, "..", "public", "site", "assets", "css");
const OUT = join(CSS_DIR, "site-template.css");

// Exact load order from the template's <head>.
const FILES = [
  "bootstrap.min.css",
  "animate.min.css",
  "custom-animate.css",
  "swiper.min.css",
  "font-awesome-all.css",
  "jarallax.css",
  "jquery.magnific-popup.css",
  "odometer.min.css",
  "flaticon.css",
  "owl.carousel.min.css",
  "owl.theme.default.min.css",
  "nice-select.css",
  "jquery-ui.css",
  "aos.css",
  "module-css/banner.css",
  "module-css/slider.css",
  "module-css/footer.css",
  "module-css/sliding-text.css",
  "module-css/category.css",
  "module-css/about.css",
  "module-css/courses.css",
  "module-css/why-choose.css",
  "module-css/live-class.css",
  "module-css/video-one.css",
  "module-css/blog.css",
  "module-css/counter.css",
  "module-css/team.css",
  "module-css/newsletter.css",
  "module-css/testimonial.css",
  "module-css/contact.css",
  "module-css/process.css",
  "module-css/page-header.css",
  "module-css/skill.css",
  "module-css/event.css",
  "module-css/pricing.css",
  "module-css/courses-search.css",
  "style.css",
  "responsive.css",
  "module-css/become-a-teacher.css",
  "module-css/shop.css",
  "module-css/faq.css",
  "module-css/error.css",
];

let out = "/* site template stylesheet bundle — generated by scripts/build-site-css.mjs. Do not edit. */\n";
for (const file of FILES) {
  const css = readFileSync(join(CSS_DIR, file), "utf8");
  // @charset is only valid as the first statement of a file; drop it so mid-file copies are not
  // emitted. UTF-8 is the default for a served stylesheet anyway.
  const cleaned = css.replace(/^﻿?@charset\s+[^;]+;\s*/i, "");
  out += `\n/* ===== ${file} ===== */\n${cleaned.trimEnd()}\n`;
}
writeFileSync(OUT, out);
console.log(`[build-site-css] wrote ${FILES.length} files -> ${OUT} (${(out.length / 1024).toFixed(0)}KB)`);
